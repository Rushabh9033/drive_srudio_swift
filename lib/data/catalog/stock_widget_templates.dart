WidgetSpec _bg(String from, String to, List<Layer> layers) {
  return WidgetSpec(
    background: WidgetBackground(type: BgType.gradient, from: from, to: to),
    layers: layers,
  );
}

WidgetSpec _solid(String color, List<Layer> layers) {
  return WidgetSpec(
    background: WidgetBackground(type: BgType.solid, from: color, to: color),
    layers: layers,
  );
}

